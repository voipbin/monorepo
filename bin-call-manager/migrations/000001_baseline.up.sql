-- Baseline of the tables owned by bin-call-manager.
-- Every statement is CREATE TABLE IF NOT EXISTS so that databases that already have the table
-- (created by the former Alembic stream) are left untouched.
-- Only call_outbound_configs carries a table option: DEFAULT CHARSET=utf8mb4 with the collation
-- utf8mb4_0900_ai_ci written out, so that it does not depend on the database default. The other
-- tables inherit the database defaults.
CREATE TABLE IF NOT EXISTS call_bridges (
  asterisk_id varchar(255) DEFAULT NULL,
  id varchar(255) NOT NULL,
  name varchar(255) DEFAULT NULL,
  type varchar(255) DEFAULT NULL,
  tech varchar(255) DEFAULT NULL,
  class varchar(255) DEFAULT NULL,
  creator varchar(255) DEFAULT NULL,
  video_mode varchar(255) DEFAULT NULL,
  video_source_id varchar(255) DEFAULT NULL,
  channel_ids json DEFAULT NULL,
  reference_type varchar(255) DEFAULT NULL,
  reference_id binary(16) DEFAULT NULL,
  record_channel_id varchar(255) DEFAULT NULL,
  record_files json DEFAULT NULL,
  tm_create datetime(6) DEFAULT NULL,
  tm_update datetime(6) DEFAULT NULL,
  tm_delete datetime(6) DEFAULT NULL,
  PRIMARY KEY (id),
  KEY idx_call_bridges_create (tm_create),
  KEY idx_call_bridges_reference_id (reference_id),
  KEY idx_call_bridges_id (id),
  KEY idx_call_bridges_asterisk_id_id (asterisk_id, id)
);
CREATE TABLE IF NOT EXISTS call_calls (
  id binary(16) NOT NULL,
  customer_id binary(16) DEFAULT NULL,
  owner_type varchar(255) DEFAULT NULL,
  owner_id binary(16) DEFAULT NULL,
  channel_id varchar(255) DEFAULT NULL,
  bridge_id varchar(255) DEFAULT NULL,
  flow_id binary(16) DEFAULT NULL,
  activeflow_id binary(16) DEFAULT NULL,
  confbridge_id binary(16) DEFAULT NULL,
  type varchar(16) DEFAULT NULL,
  master_call_id binary(16) DEFAULT NULL,
  chained_call_ids json DEFAULT NULL,
  recording_id binary(16) DEFAULT NULL,
  recording_ids json DEFAULT NULL,
  external_media_ids json DEFAULT (JSON_ARRAY()),
  groupcall_id binary(16) DEFAULT NULL,
  source json DEFAULT NULL,
  source_target varchar(1024) DEFAULT NULL,
  destination json DEFAULT NULL,
  destination_target varchar(1024) DEFAULT NULL,
  status varchar(255) DEFAULT NULL,
  data json DEFAULT NULL,
  metadata json DEFAULT NULL,
  action json DEFAULT NULL,
  action_next_hold tinyint(1) DEFAULT 0,
  direction varchar(16) DEFAULT NULL,
  mute_direction varchar(16) DEFAULT NULL,
  hangup_by varchar(16) DEFAULT NULL,
  hangup_reason varchar(16) DEFAULT NULL,
  dialroute_id binary(16) DEFAULT 0x00000000000000000000000000000000,
  dialroutes json DEFAULT NULL,
  tm_create datetime(6) DEFAULT NULL,
  tm_update datetime(6) DEFAULT NULL,
  tm_delete datetime(6) DEFAULT NULL,
  tm_progressing datetime(6) DEFAULT NULL,
  tm_ringing datetime(6) DEFAULT NULL,
  tm_hangup datetime(6) DEFAULT NULL,
  PRIMARY KEY (id),
  KEY idx_call_calls_customer_id (customer_id),
  KEY idx_call_calls_owner_id (owner_id),
  KEY idx_call_calls_channel_id (channel_id),
  KEY idx_call_calls_flow_id (flow_id),
  KEY idx_call_calls_create (tm_create),
  KEY idx_call_calls_hangup (tm_hangup),
  KEY idx_call_calls_source_target (source_target),
  KEY idx_call_calls_destination_target (destination_target),
  KEY idx_call_calls_groupcall_id (groupcall_id),
  KEY idx_call_calls_activeflow_id (activeflow_id)
);
