  status varchar(16) DEFAULT NULL,
  flow_id binary(16) DEFAULT NULL,
  source json DEFAULT NULL,
  destinations json DEFAULT NULL,
  master_call_id binary(16) DEFAULT NULL,
  master_groupcall_id binary(16) DEFAULT NULL,
  ring_method varchar(255) DEFAULT NULL,
  answer_method varchar(255) DEFAULT NULL,
  anonymous varchar(10) NOT NULL DEFAULT '',
