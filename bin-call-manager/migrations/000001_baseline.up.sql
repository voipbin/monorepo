  dst_number varchar(255) DEFAULT NULL,
  state varchar(255) DEFAULT NULL,
  data json DEFAULT NULL,
  stasis_name varchar(255) DEFAULT NULL,
  stasis_data json DEFAULT NULL,
  bridge_id varchar(255) DEFAULT NULL,
  playback_id varchar(255) DEFAULT NULL,
  dial_result varchar(255) DEFAULT NULL,
  hangup_cause int(11) DEFAULT NULL,
  direction varchar(255) DEFAULT NULL,
  mute_direction varchar(16) DEFAULT NULL,
  tm_create datetime(6) DEFAULT NULL,
  tm_update datetime(6) DEFAULT NULL,
