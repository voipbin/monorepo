// Test_publishFakeEventChannelDestoryed_roundtrip checks the published payload is an event that the subscribe handler
// can route: it parses to a typed ChannelDestroyed event with the channel id and the normal clearing cause.
// An untyped event parses to nothing and is dropped by the router.
func Test_publishFakeEventChannelDestoryed_roundtrip(t *testing.T) {
	mc := gomock.NewController(t)
	defer mc.Finish()

	mockReq := requesthandler.NewMockRequestHandler(mc)
	h := channelHandler{
		reqHandler: mockReq,
	}
	ctx := context.Background()
	channelID := "7c9f1cf8-defa-11ee-84f7-dbd9ffcc4b6e"

	var published []byte
	mockReq.EXPECT().CallPublishEvent(ctx, string(ari.EventTypeChannelDestroyed), "asterisk-proxy", "application/json", gomock.Any()).
		DoAndReturn(func(_ context.Context, _ string, _ string, _ string, data []byte) error {
			published = data
			return nil
		})

	h.publishFakeEventChannelDestoryed(ctx, channelID)

	event, evt, err := ari.Parse(published)
	if err != nil {
		t.Fatalf("Wrong match. expect: ok, got: %v", err)
	}
	if event.Type != ari.EventTypeChannelDestroyed {
		t.Fatalf("Wrong event type. expect: %v, got: %v", ari.EventTypeChannelDestroyed, event.Type)
	}

	destroyed, ok := evt.(*ari.ChannelDestroyed)
	if !ok {
		t.Fatalf("Wrong event struct. expect: *ari.ChannelDestroyed, got: %T", evt)
	}
	if destroyed.Channel.ID != channelID {
		t.Errorf("Wrong channel id. expect: %s, got: %s", channelID, destroyed.Channel.ID)
	}
	if destroyed.Cause != ari.ChannelCauseNormalClearing {
		t.Errorf("Wrong cause. expect: %v, got: %v", ari.ChannelCauseNormalClearing, destroyed.Cause)
	}
}

