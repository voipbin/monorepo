-- Baseline of the tables owned by bin-billing-manager.
-- Every statement is CREATE TABLE IF NOT EXISTS so that databases that already have the table
-- (created by the former Alembic stream) are left untouched.
-- No table options are given on purpose: the database defaults are inherited, as Alembic did.
CREATE TABLE IF NOT EXISTS billing_accounts (
  id binary(16) NOT NULL,
  customer_id binary(16) DEFAULT NULL,
  status varchar(16) NOT NULL DEFAULT 'active',
  plan_type varchar(255) NOT NULL DEFAULT 'free',
  plan_status varchar(32) NOT NULL DEFAULT 'active',
  name varchar(255) DEFAULT NULL,
  detail text DEFAULT NULL,
  payment_type varchar(255) DEFAULT NULL,
  payment_method varchar(255) DEFAULT NULL,
  tm_create datetime(6) DEFAULT NULL,
  tm_update datetime(6) DEFAULT NULL,
  tm_delete datetime(6) DEFAULT NULL,
  balance_credit bigint NOT NULL DEFAULT 0,
  balance_token bigint NOT NULL DEFAULT 0,
  tm_last_topup datetime DEFAULT NULL,
  tm_next_topup datetime DEFAULT NULL,
  paddle_subscription_id varchar(255) DEFAULT NULL,
  paddle_customer_id varchar(255) DEFAULT NULL,
  PRIMARY KEY (id),
  KEY idx_billing_accounts_customer_id (customer_id),
  KEY idx_billing_accounts_create (tm_create),
  KEY idx_billing_accounts_status (status),
  KEY ix_billing_accounts_paddle_subscription_id (paddle_subscription_id),
  KEY ix_billing_accounts_paddle_customer_id (paddle_customer_id)
);
CREATE TABLE IF NOT EXISTS billing_billings (
  id binary(16) NOT NULL,
  customer_id binary(16) DEFAULT NULL,
  account_id binary(16) DEFAULT NULL,
  status varchar(32) DEFAULT NULL,
  reference_type varchar(32) DEFAULT NULL,
  reference_id binary(16) DEFAULT NULL,
  tm_billing_start datetime(6) DEFAULT NULL,
  tm_billing_end datetime(6) DEFAULT NULL,
  tm_create datetime(6) DEFAULT NULL,
  tm_update datetime(6) DEFAULT NULL,
  tm_delete datetime(6) DEFAULT NULL,
  cost_type varchar(32) NOT NULL DEFAULT '',
  transaction_type varchar(32) NOT NULL DEFAULT 'usage',
  usage_duration int NOT NULL DEFAULT 0,
  billable_units int NOT NULL DEFAULT 0,
  rate_token_per_unit bigint NOT NULL DEFAULT 0,
  rate_credit_per_unit bigint NOT NULL DEFAULT 0,
  amount_token bigint NOT NULL DEFAULT 0,
  amount_credit bigint NOT NULL DEFAULT 0,
  balance_token_snapshot bigint NOT NULL DEFAULT 0,
  balance_credit_snapshot bigint NOT NULL DEFAULT 0,
  idempotency_key varbinary(16) DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY idx_billing_billings_ref_type_ref_id (reference_type,reference_id),
  UNIQUE KEY ux_billing_billings_idempotency_key (idempotency_key),
  KEY idx_billing_billings_customer_id (customer_id),
  KEY idx_billing_billings_account_id (account_id),
  KEY idx_billing_billings_reference_id (reference_id),
  KEY idx_billing_billings_create (tm_create)
);
CREATE TABLE IF NOT EXISTS billing_failed_events (
  id binary(16) NOT NULL,
  event_type varchar(255) NOT NULL,
  event_publisher varchar(255) NOT NULL,
  event_data text NOT NULL,
  error_message text NOT NULL,
  retry_count int NOT NULL DEFAULT 0,
  max_retries int NOT NULL DEFAULT 5,
  next_retry_at datetime(6) NOT NULL,
  status varchar(32) NOT NULL DEFAULT 'pending',
  tm_create datetime(6) DEFAULT NULL,
  tm_update datetime(6) DEFAULT NULL,
  PRIMARY KEY (id),
  KEY idx_billing_failed_events_status_next_retry (status,next_retry_at)
);
